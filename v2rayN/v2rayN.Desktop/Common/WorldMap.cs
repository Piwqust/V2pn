using System.Text.RegularExpressions;
using System.Collections.Concurrent;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace v2rayN.Desktop.Common;

public sealed class MapCountry
{
    [JsonPropertyName("ru")] public string Ru { get; set; } = "";
    [JsonPropertyName("en")] public string En { get; set; } = "";
    [JsonPropertyName("x")] public double X { get; set; }
    [JsonPropertyName("y")] public double Y { get; set; }
    [JsonPropertyName("b")] public double[] Bounds { get; set; } = [];
    [JsonPropertyName("d")] public string Path { get; set; } = "";

    [JsonIgnore] public string Code { get; set; } = "";

    [JsonIgnore]
    public string Name
    {
        get
        {
            var ui = CultureInfo.CurrentUICulture;
            if (ui.Name.StartsWith("ru", StringComparison.OrdinalIgnoreCase))
            {
                return Ru;
            }
            if (ui.Name.StartsWith("en", StringComparison.OrdinalIgnoreCase) || ui == CultureInfo.InvariantCulture)
            {
                return En;
            }
            return WorldMap.Instance.LocalizedName(Code, ui) ?? En;
        }
    }
}

/// <summary>
/// Mercator world map generated by tools/mapgen from Natural Earth data: country outlines,
/// pin positions and bounds in a fixed pixel space.
/// </summary>
public sealed class WorldMap
{
    private sealed class MapFile
    {
        [JsonPropertyName("width")] public double Width { get; set; }
        [JsonPropertyName("height")] public double Height { get; set; }
        [JsonPropertyName("countries")] public Dictionary<string, MapCountry> Countries { get; set; } = [];
    }

    private static readonly Lazy<WorldMap> _instance = new(Load);
    public static WorldMap Instance => _instance.Value;

    public double Width { get; private init; }
    public double Height { get; private init; }
    public IReadOnlyDictionary<string, MapCountry> Countries { get; private init; } = new Dictionary<string, MapCountry>();

    // UI language -> country code -> name, for the languages world.json has no names for.
    private readonly Lazy<Dictionary<string, Dictionary<string, string>>> _names = new(LoadNames);

    public string? LocalizedName(string code, CultureInfo culture)
    {
        for (var c = culture; !string.IsNullOrEmpty(c.Name); c = c.Parent)
        {
            if (_names.Value.TryGetValue(c.Name, out var map) && map.TryGetValue(code, out var name))
            {
                return name;
            }
        }
        return null;
    }

    private static Dictionary<string, Dictionary<string, string>> LoadNames()
    {
        try
        {
            using var stream = AssetLoader.Open(new Uri("avares://V2pn/Assets/Map/names.json"));
            var names = JsonSerializer.Deserialize<Dictionary<string, Dictionary<string, string>>>(stream) ?? [];
            return new(names, StringComparer.OrdinalIgnoreCase);
        }
        catch (Exception ex)
        {
            Logging.SaveLog("WorldMap names", ex);
            return [];
        }
    }

    public MapCountry? Get(string? code) =>
        code != null && Countries.TryGetValue(code.ToUpperInvariant(), out var c) ? c : null;

    // The latitude tools/mapgen puts at the top edge: the canvas starts at the Arctic.
    private const double TopLatitude = 83.5;

    /// <summary>A longitude and latitude in the map's pixel space, with the projection tools/mapgen uses.</summary>
    public Point Project(double lon, double lat)
    {
        var scale = Width / (2 * Math.PI);
        var top = -scale * Math.Log(Math.Tan((Math.PI / 4) + (TopLatitude * Math.PI / 360)));
        var y = -scale * Math.Log(Math.Tan((Math.PI / 4) + (Math.Clamp(lat, -85, 85) * Math.PI / 360)));
        return new Point((Width / 2) + (scale * lon * Math.PI / 180), y - top);
    }

    /// <summary>Where a country's dot stands: a representative city for the few countries whose middle misleads.</summary>
    public Point? Anchor(string? code)
    {
        if (MapCities.Representative(code) is { } city)
        {
            return Project(city.Lon, city.Lat);
        }
        return Get(code) is { } country ? new Point(country.X, country.Y) : null;
    }

    private static WorldMap Load()
    {
        try
        {
            using var stream = AssetLoader.Open(new Uri("avares://V2pn/Assets/Map/world.json"));
            var file = JsonSerializer.Deserialize<MapFile>(stream) ?? new MapFile();
            var countries = new Dictionary<string, MapCountry>(StringComparer.OrdinalIgnoreCase);
            foreach (var (code, country) in file.Countries)
            {
                country.Code = code.ToUpperInvariant();
                countries[country.Code] = country;
            }
            return new WorldMap { Width = file.Width, Height = file.Height, Countries = countries };
        }
        catch (Exception ex)
        {
            Logging.SaveLog("WorldMap", ex);
            return new WorldMap { Width = 2400, Height = 1560 };
        }
    }
}

/// <summary>
