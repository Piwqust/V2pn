    public static string? Resolve(string? remarks)
    {
        if (remarks.IsNullOrEmpty())
        {
            return null;
        }
        return _cache.GetOrAdd(remarks, Detect);
    }

    /// <summary>
    /// The name to show for a server: its remark without flag emoji, or, when a link came with no
    /// name at all, its address, so a row or the header is never blank.
    /// </summary>
    public static string ServerName(ProfileItem item) => ServerName(item.Remarks, item.Address, item.ConfigType, item.Subid);

    public static string ServerName(ProfileItemModel item) => ServerName(item.Remarks, item.Address, item.ConfigType, item.Subid);

    private static string ServerName(string? remarks, string? address, EConfigType type, string? subId)
    {
        var name = StripFlag(remarks);
        if (name.IsNotEmpty())
        {
            return name;
        }
        // V2pn: a partner that closed its settings keeps its addresses out of sight, names included.
        if (V2pnLocks.Instance.Hides(subId))
        {
            return L.ServerUnnamed;
        }
        return address.IsNotEmpty() ? address! : type.ToString();
    }

    /// <summary>
    /// The server's name without the country the header already shows above it: "Швеция — напрямую" under "Sweden"
    /// reads "напрямую". The name stays whole when nothing would be left of it.
    /// </summary>
    public static string WithoutCountry(string name, string? code)
    {
        if (name.IsNullOrEmpty() || code.IsNullOrEmpty() || WorldMap.Instance.Get(code) is not { } country)
        {
            return name;
        }
        var result = name;
        foreach (var word in new[] { country.Ru, country.En, country.Name }.Where(w => w.Length >= 3).Distinct())
        {
            result = Regex.Replace(result, $@"(?<![\p{{L}}]){Regex.Escape(word)}(?![\p{{L}}])", " ", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
        }
        return TidySeparators(result) is { Length: > 0 } left ? left : name;
    }

    /// <summary>Takes out separators left at the ends or twice in a row once words are removed from a name.</summary>
    public static string TidySeparators(string text)
    {
        var result = Regex.Replace(text, @"\s+", " ");
        result = Regex.Replace(result, @"\s*([·|—–\-,:])(\s*[·|—–\-,:])+\s*", " $1 ");
        return result.Trim().Trim('·', '|', '—', '–', '-', ',', ':', ' ').Trim();
    }

    /// <summary>Removes flag emoji so the image flag beside the name is not duplicated.</summary>
    public static string StripFlag(string? remarks)
    {
        if (remarks.IsNullOrEmpty())
        {
            return string.Empty;
        }
        var sb = new StringBuilder(remarks.Length);
        foreach (var rune in remarks.EnumerateRunes())
        {
            if (rune.Value is >= 0x1F1E6 and <= 0x1F1FF)
            {
                continue;
            }
            sb.Append(rune.ToString());
        }
        return sb.ToString().Trim().TrimStart('|', '-', '·', ' ').Trim();
    }

    private static string? Detect(string remarks)
    {
        // 1. Regional-indicator pair, e.g. 🇳🇱.
        var indicators = new List<char>(2);
        foreach (var rune in remarks.EnumerateRunes())
        {
            if (rune.Value is >= 0x1F1E6 and <= 0x1F1FF)
            {
                indicators.Add((char)('A' + rune.Value - 0x1F1E6));
                if (indicators.Count == 2)
                {
                    var code = new string([.. indicators]);
                    return code == "UK" ? "GB" : code;
                }
            }
            else
            {
                indicators.Clear();
            }
        }

        // 2. Country or city name.
        var (regex, lookup) = _names.Value;
        var match = regex.Match(remarks);
        if (match.Success && lookup.TryGetValue(match.Value.ToLowerInvariant(), out var byName))
        {
            return byName;
        }

        // 3. Upper-case ISO code token.
        foreach (var token in Regex.Split(remarks, @"[^A-Za-z]+"))
        {
            if (token.Length == 2 && token.All(char.IsUpper) && !_ambiguous.Contains(token))
            {
                var code = token == "UK" ? "GB" : token;
                if (WorldMap.Instance.Get(code) != null)
                {
                    return code;
                }
            }
        }
        return null;
    }

    private static (Regex, Dictionary<string, string>) BuildNames()
    {
        var lookup = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (code, c) in WorldMap.Instance.Countries)
        {
            foreach (var name in new[] { c.Ru, c.En })
            {
                if (name.Length >= 4)
                {
                    lookup.TryAdd(name.ToLowerInvariant(), code);
                }
            }
        }
        foreach (var (name, code) in _aliases)
        {
            lookup[name.ToLowerInvariant()] = code;
        }
        var pattern = string.Join("|", lookup.Keys.OrderByDescending(k => k.Length).Select(Regex.Escape));
        var regex = new Regex($@"(?<![\p{{L}}])(?:{pattern})(?![\p{{L}}])", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant | RegexOptions.Compiled);
        return (regex, lookup);
    }
}
